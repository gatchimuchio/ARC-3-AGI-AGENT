"""観測された進行と完成時刻の一意性を分離する。外部作用権限なし。"""
def 進行証拠をまとめる(相記録, 目標照合群):
    """各目標照合は既存HDS/知覚境界の照会結果。未確認は成功へ補完しない。"""
    証拠=[];保留=[];相数=len(相記録['応答全盤面']);使用済み=set()
    for r in 目標照合群:
        n=r.get('相')
        if type(n) is not int or not 0<=n<相数 or n in 使用済み:
            保留.append({'照合対応不正':r});continue
        使用済み.add(n)
        if r.get('旧構造一致') is True and r.get('目標判定')=='条件付き目標一致':証拠.append(r)
    境界保留=list(相記録['保留理由群'])+保留
    増分=相記録['完了数増分'];増分あり=type(増分) is int and 増分>0
    支持=増分あり and bool(証拠) and not 境界保留
    return {'進行判定':'公開完了増分と旧目標充足の支持あり' if 支持 else '追加照合が必要',
            '観測完了数増分':増分,'旧目標充足の全証拠':証拠,'全相照合':目標照合群,
            '未照合相':sorted(set(range(相数))-使用済み),'完成時刻の一意性':'一意未確認' if len(証拠)!=1 else '一つの可視候補のみ。原始時刻は未確定',
            '完成相を選ぶ必要性':'進行支持に単一indexを要求しない','作用因果確定':False,
            '境界保留':境界保留,'実行許可':False}

from .共通観測経路 import 作用応答を相別に記録する, _画素差分, 作用適用性を読む
from .列図式規則 import 図式を観測する, 照会, 一致する, 役割境界, 目標境界
from .複合図式規則 import 複合図式を読む, 本体対象群を読む
from .図式許容集合 import 許容集合を含む図式攻略を照会する
from .ARC3境界 import _盤面列

def _構造(語彙,盤面):
    if 語彙=='列展開':
        p=図式を観測する(盤面)
        return {'目標列':p['目標列'],'容器構造':[{'色':c['色'],'位置':c['位置'],'起点':c['起点'],'枠位置':[s['位置'] for s in c['枠群']]} for c in p['容器群']]},p
    p=複合図式を読む(盤面)
    if 'HOLD' in p:raise ValueError(str(p))
    return {'色列':p['色列'],'格子位相群':p['格子位相群'],'指示参照':[{'対象位置':t['対象位置'],'中心色':t['中心色'],'記号順位':t['記号順位']} for t in p['参照対象群']]},p

def 公開応答相を照合する(学習系,直前,現在,作用番号,旧語彙結果,*,図式適用支持=None,予測盤面=None):
    """旧共通照会の構造適用性を引き継ぎ、全相へ既存の目標照会を適用。

    旧語彙結果は公開観測から候補を照会するの出力。完成答えではない。
    予測盤面は旧観測から構成済みの全画素モデル予測だけを受け取り、各相と
    比較する。予測の生成主体/根拠は呼出元の候補台帳で保持する。
    """
    相記録=作用応答を相別に記録する(直前,現在,作用番号)
    結果={'相記録':相記録,'相別目標照合':[],'相別予測差分照合':[],'照会記録':[],
          '保留理由群':list(相記録['保留理由群']),'進行証拠':None,'実行許可':False}
    保留=結果['保留理由群'];記録=結果['照会記録']
    if 旧語彙結果.get('出所',{}).get('観測通番')!=直前.観測通番 or 旧語彙結果.get('出所',{}).get('観測指紋')!=直前.指紋:
        保留.append('旧語彙照会が直前観測に対応しない')
    if 旧語彙結果.get('規則不確実性'):保留.append({'HDS隔離':旧語彙結果['規則不確実性']})
    if not 保留:
        if 予測盤面 is not None:
            try:予測=_盤面列([予測盤面])[0]
            except Exception as e:保留.append({'予測盤面不正':str(e)});return 結果
            for i,f in enumerate(現在.盤面列):
                差分=_画素差分(予測,f);結果['相別予測差分照合'].append({'相':i,'全画素残差':差分,'全画素一致':差分['状態']=='比較可能' and not 差分['差分'],'因果確定':False})
    結果['語彙適用境界']=[{'語彙':x['語彙'],'目標適用性':x['結果'].get('適用性'),'作用適用性':作用適用性を読む(x['結果'])} for x in 旧語彙結果.get('語彙別結果',[])]
    語彙群=[x['語彙'] for x in 旧語彙結果.get('語彙別結果',[]) if 作用適用性を読む(x['結果'])['状態']=='適用可能']
    未確認=[x for x in 旧語彙結果.get('語彙別結果',[]) if 作用適用性を読む(x['結果'])['状態']=='未確認']
    if len(語彙群)!=1 or 未確認:保留.append('旧問題の適用語彙が一意に確認できない')
    if 保留:return 結果
    語彙=語彙群[0]
    if 語彙 not in ('列展開','複合配色'):保留.append('目標相照合の語彙が未対応');return 結果
    try:旧構造,旧解析=_構造(語彙,直前.最新盤面)
    except Exception as e:保留.append({'旧構造解析未確認':str(e)});return 結果
    役割={};受理=None
    if 語彙=='列展開':
        for 中空 in (False,True):
            役割[中空],q=照会(学習系,役割境界,{'記号は中空':中空},'列展開役割');記録.append(q)
        受理,q=照会(学習系,目標境界,{'終端条件に応じた列が一致':True},'提出が受理された');記録.append(q)
    旧目標=None
    if 語彙=='複合配色':
        旧目標=許容集合を含む図式攻略を照会する(直前.最新盤面,直前.作用可能番号,学習系,図式適用支持)
        記録.append({'旧公開問題の目標再照会':旧目標})
    for i,f in enumerate(現在.盤面列):
        r={'相':i,'目標判定':'未確認'};結果['相別目標照合'].append(r)
        try:構造,解析=_構造(語彙,f)
        except Exception as e:r['解析未確認']=str(e);continue
        r['旧構造一致']=構造==旧構造
        if not r['旧構造一致']:continue
        if 語彙=='列展開':
            if any(v is None for v in 役割.values()) or 受理 is not True:r['保留']='HDS目標関係未支持';continue
            一致,詳細=一致する(解析,役割);r['展開証拠']=詳細
        else:
            if 旧目標['保留理由群'] or 旧目標.get('規則の不確実性'):
                r['保留']=旧目標['保留理由群'];continue
            現対象=本体対象群を読む(f,解析);旧対象=本体対象群を読む(直前.最新盤面,旧解析);制約=旧目標['目標候補群'];対象照合=[]
            for c in 制約:
                鍵=tuple(c['位置']);現在対象=現対象.get(鍵)
                if 現在対象 is None or 現在対象['幅']!=c['幅'] or 現在対象['本体画素']!=c['本体画素'] or 現在対象['標識画素']!=旧対象.get(鍵,{}).get('標識画素'):
                    対象照合.append({'対象':鍵,'状態':'対象対応未確認'});continue
                許容=c.get('許容色集合',[c.get('予測色')])
                対象照合.append({'対象':鍵,'状態':'一致' if all(f[y][x] in 許容 for x,y in c['本体画素']) else '不一致','許容色集合':許容})
            r['対象目標照合']=対象照合
            一致=bool(対象照合) and all(c['状態']=='一致' for c in 対象照合)
        r['目標判定']='条件付き目標一致' if 一致 else '目標不一致又は未確認'
    結果['進行証拠']=進行証拠をまとめる(相記録,結果['相別目標照合'])
    return 結果
