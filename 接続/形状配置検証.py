"""予測構造モデルの公開前後照合。入力盤面と証拠を保持し、観測欠損は保留する。"""
from .形状配置知覚 import 初期対象を読む, 全整合分解を読む
from .形状配置規則 import 方向候補, 規則を照会する, 局所前提を読む, 局所前提を符号化する, 投射前提を読む, 局所境界, 投射境界, 選択境界

def _構造(対象群):
    return sorted((tuple(対象['形']),tuple(対象['位置']),対象['選択']) for 対象 in 対象群)

def 公開前後でモデルを検証する(学習系, 問題盤面, 前後例):
    初期=初期対象を読む(問題盤面);形状在庫=[対象['形'] for 対象 in 初期['対象']]
    背景=[行[:] for 行 in 問題盤面]
    for 対象 in 初期['対象']:
        for 横,縦 in 対象['点']:背景[縦][横]=1
    for 目標 in 初期['目標']:
        for 横,縦 in 目標['外枠']:背景[縦][横]=4
    記録=[];背景不一致=[];露出=set()
    for 例 in 前後例:
        前盤面,後盤面=例['前盤面'],例['後盤面'];作用=例['作用_外部契約'];番号=作用['id']
        前候補=全整合分解を読む(前盤面,形状在庫);後候補=全整合分解を読む(後盤面,形状在庫)
        共通={'前行':例['前行'],'後行':例['後行'],'作用番号':番号,'前可視分解':前候補,'後可視分解':後候補}
        if 原票境界が不成立(例,番号) or len(前候補)!=1 or len(後候補)!=1:
            記録.append({**共通,'状態':'保留','理由':'原票境界または可視分解が未確定'});continue
        前,後=前候補[0],後候補[0];予測=[dict(対象) for 対象 in 前];選択=next(番号 for 番号,対象 in enumerate(前) if 対象['選択']);理由=None
        if 番号==6:
            座標=(作用['data'].get('x'),作用['data'].get('y'));包含=[番号 for 番号,対象 in enumerate(前) if 座標 in 対象['点']]
            照会=規則を照会する(学習系,{'座標がこの対象に含まれる':True},選択境界,'作用後この対象が選択される')
            if len(包含)!=1 or 照会['値'] is not True:理由='選択未支持'
            else:
                for 対象番号,対象 in enumerate(予測):対象['選択']=対象番号==包含[0]
        elif 番号 in 方向候補:
            横差,縦差=方向候補[番号];対象=前[選択]
            照会=規則を照会する(学習系,局所前提を符号化する(局所前提を読む(前盤面,対象,番号),'直積記号'),局所境界,'入力方向へ一単位進む')
            if 照会['値'] is None:理由='局所未支持'
            elif 照会['値'] is True:予測[選択]['位置']=(対象['位置'][0]+横差,対象['位置'][1]+縦差)
            次領域={(横+横差,縦+縦差) for 横,縦 in 対象['点']};接触=[索引 for 索引,他 in enumerate(前) if 索引!=選択 and 次領域&他['点']]
            if len(接触)>1:理由='複数接触未支持'
            if len(接触)==1:
                索引=接触[0];照会=規則を照会する(学習系,投射前提を読む(前盤面,対象,前[索引],番号),投射境界,'接触対象変位')
                if 照会['値'] is None:理由='投射未支持'
                else:
                    前方,側方=map(int,照会['値'].split(','));横単位,縦単位=横差//3,縦差//3;横,縦=前[索引]['位置'];予測[索引]['位置']=(横+前方*横単位-側方*縦単位,縦+前方*縦単位+側方*横単位)
        else:理由='作用語彙外'
        記録.append({**共通,'状態':'保留' if 理由 else '一致' if _構造(予測)==_構造(後) else '不一致','理由':理由,'予測構造':_構造(予測),'実測構造':_構造(後)})
        占有=set().union(*(対象['点'] for 対象 in 後))
        for 縦 in range(63):
            for 横 in range(64):
                if (横,縦) in 占有:continue
                if 後盤面[縦][横]!=背景[縦][横]:背景不一致.append({'後行':例['後行'],'位置':[横,縦],'予測':背景[縦][横],'実測':後盤面[縦][横]})
                if any((横,縦) in 対象['点'] for 対象 in 初期['対象']):露出.add((横,縦))
    初期遮蔽=set().union(*(対象['点'] for 対象 in 初期['対象']))
    成立=bool(記録) and all(例['状態']=='一致' for 例 in 記録) and not 背景不一致 and 露出==初期遮蔽
    return {'状態':'照合成立' if 成立 else '保留','全前後照合':記録,'背景不一致':背景不一致,'初期遮蔽画素数':len(初期遮蔽),'露出確認画素数':len(露出),'固定仮定':'移動跡は床/既知輪郭へ復帰。画面端UIと矢印の画素アニメーションは対象外。','実行許可':False}

def 原票境界が不成立(例,番号):
    return not (例['同じ実行'] and 例['同じゲーム'] and not 例['全初期化'] and 番号 in 例['前作用可能番号'])
