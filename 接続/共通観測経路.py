"""公開観測から構造語彙を全照会する。語彙の選択にIDを用いない。

同一HDSを注入し、既存の採否・隔離を保持する。環境排出は行わない。
"""
from .ARC3境界 import _盤面列, _作用番号, _整数, 境界違反
from .列図式規則 import 候補を構成する as 列図式候補
from .追加語彙接続 import 鎖語彙を接続する, 形状語彙を接続する
from .図式許容集合 import 許容集合を含む図式攻略を照会する as 複合図式候補

def _作用候補を共通化する(候補, 作用群):
    if not isinstance(候補, dict) or 候補.get('実行許可') is not False:
        raise 境界違反('未実行候補の契約に違反')
    番号 = _作用番号(候補.get('作用番号'))
    if 番号 not in 作用群: raise 境界違反('候補作用が現在の利用可能作用にない')
    引数 = 候補.get('引数', {})
    if '座標' in 候補:
        座標 = 候補['座標']
        if not isinstance(座標, (list, tuple)) or len(座標) != 2: raise 境界違反('座標候補の形式不明')
        座標引数 = {'x': 座標[0], 'y': 座標[1]}
        if 引数 and 引数 != 座標引数: raise 境界違反('二つの作用引数表現が矛盾')
        引数 = 座標引数
    if not isinstance(引数, dict): raise 境界違反('作用引数が辞書でない')
    if 番号 == 6:
        if set(引数) != {'x', 'y'}: raise 境界違反('座標作用の引数不正')
        for 軸 in ('x', 'y'): _整数(引数[軸], 軸, 0, 63)
    elif 引数: raise 境界違反('非座標作用に余分な引数がある')
    return {'作用番号': 番号, '引数': dict(引数), '元候補': 候補, '実行許可': False}


def 公開観測から候補を照会する(学習系, 現在, *, 図式適用支持=None):
    """同じ公開観測へ全語彙を照会し、次作用と後続経路を混同しない。"""
    結果 = {'状態': '未確認', '語彙別結果': [], '次作用候補群': [], '候補経路群': [],
          '全目標候補群': [], '規則不確実性': [], '保留理由群': [], '未採用理由群': [],
          '複数整合解': [], '出所': {'観測通番': 現在.観測通番, '観測指紋': 現在.指紋},
          '実行許可': False}
    if 現在.状態 != 'NOT_FINISHED':
        結果['状態'] = {'NOT_PLAYED': '開始前観測', 'GAME_OVER': '停止観測', 'WIN': '完了観測'}.get(現在.状態, '不明状態観測')
        結果['保留理由群'].append({'状態境界': 現在.状態}); return 結果
    try:
        盤面 = _盤面列([現在.最新盤面])[0]
        作用群 = tuple(_作用番号(v) for v in 現在.作用可能番号)
        if len(set(作用群)) != len(作用群): raise 境界違反('利用可能作用が重複')
    except (境界違反, TypeError, IndexError) as exc:
        結果['保留理由群'].append({'観測境界': str(exc)}); return 結果
    # 順序は優先順位ではない。すべて実行し、複数解釈を黙って一つにしない。
    語彙群 = [('列展開', lambda: 列図式候補(学習系, 盤面, 作用可能番号=作用群), '次作用群'),
             ('複合配色', lambda: 複合図式候補(盤面, 作用群, 学習系, 図式適用支持), '順序付き経路'),
             ('根付き順序鎖', lambda: 鎖語彙を接続する(学習系, 盤面, 作用群), '全段階経路'),
             ('形状目標対応', lambda: 形状語彙を接続する(学習系, 盤面, 作用群), '全段階経路')]
    適用群 = []; 未確認群 = []
    for 語彙, 照会, 作用形式 in 語彙群:
        try:
            候補 = 照会()
            if not isinstance(候補, dict) or 候補.get('適用性', {}).get('状態') not in ('適用可能', '構造上不適用', '未確認'):
                raise ValueError('語彙の適用性契約が不明')
            if 候補.get('実行許可') is not False or not isinstance(候補.get('作用候補群'), list):
                raise ValueError('候補専用の実行権限/作用群契約に違反')
        except Exception as exc:
            # エラーを不適用へ隠さない。外部作用は常に未許可。
            候補 = {'適用性': {'状態': '未確認', '根拠': [{'例外': type(exc).__name__, '理由': str(exc)}]},
                  '目標候補群': [], '作用候補群': [], '保留理由群': ['語彙照会が完了していない'], '実行許可': False}
        記録 = {'語彙': 語彙, '作用候補の意味': 作用形式, '結果': 候補}
        結果['語彙別結果'].append(記録)
        結果['全目標候補群'].append({'語彙': 語彙, '候補群': 候補.get('目標候補群', [])})
        不確実 = 候補.get('規則不確実性', 候補.get('規則の不確実性', []))
        if 不確実: 結果['規則不確実性'].append({'語彙': 語彙, '理由': 不確実})
        複数 = 候補.get('複数整合解')
        if 複数 is True or isinstance(複数, dict) and 複数.get('候補数', 0) > 1:
            結果['複数整合解'].append({'語彙': 語彙, '候補集合': 複数})
        作用適用 = 候補.get('作用適用性', 候補['適用性'])
        if 作用適用.get('状態') not in ('適用可能', '構造上不適用', '未確認'):
            作用適用 = {'状態':'未確認','根拠':['作用適用性契約が不明']}
        適用 = 作用適用['状態']
        if 適用 == '適用可能': 適用群.append(記録)
        elif 適用 == '未確認': 未確認群.append(記録)
        else: 結果['未採用理由群'].append({'語彙': 語彙, '理由': 作用適用})
    if 結果['規則不確実性']:
        結果['状態'] = 'HDS保留'; 結果['保留理由群'].append('同一HDSの不確実性を全体に保持'); return 結果
    if 未確認群:
        結果['保留理由群'].append({'未確認語彙': [r['語彙'] for r in 未確認群]}); return 結果
    if not 適用群:
        結果['状態'] = '適用語彙なし'; return 結果
    if len(適用群) != 1:
        結果['保留理由群'].append({'複数の構造解釈': [r['語彙'] for r in 適用群]}); return 結果
    適用 = 適用群[0]; 候補 = 適用['結果']; 作用 = 候補.get('作用候補群', [])
    if '作用段階経路群' in 候補:
        # 局所保留経路も原形で保存する。支持済み経路の全段階を検査し、
        # 現在の次作用は各経路の先頭段階だけ。代表座標への切り詰めはしない。
        for 経路 in 候補['作用段階経路群']:
            記録 = {'語彙':適用['語彙'],'根拠':経路,'段階群':[], '実行許可':False}
            結果['候補経路群'].append(記録)
            if 経路.get('採否') not in ('両規則支持','全段支持') or 経路.get('保留理由群'):
                記録['採否']='保留'; 結果['未採用理由群'].append({'経路参照':経路.get('経路参照'),'理由':経路.get('保留理由群',[])}); continue
            try:
                if 経路.get('実行許可') is not False or 経路.get('全目標充足') is not True:
                    raise 境界違反('経路の目標照合が未成立')
                for 段階 in 経路['段階群']:
                    if 段階.get('実行許可') is not False or not 段階.get('作用候補群'):
                        raise 境界違反('段階の作用が未成立')
                    記録['段階群'].append({'作用候補群':[_作用候補を共通化する(a,作用群) for a in 段階['作用候補群']], '根拠':段階,'実行許可':False})
                記録['採否']='条件付き支持'
                if 記録['段階群']:
                    結果['次作用候補群'] += [{'語彙':適用['語彙'],'候補':a,'支持経路参照':経路.get('経路参照'),
                       '理由':'全段支持経路の先頭候補。毎手再観測が必要','実行許可':False} for a in 記録['段階群'][0]['作用候補群']]
            except (境界違反, KeyError, TypeError) as exc:
                記録['採否']='保留';記録['保留理由']=str(exc)
                結果['未採用理由群'].append({'経路参照':経路.get('経路参照'),'理由':str(exc)})
        結果['状態']='条件付き候補' if 結果['次作用候補群'] else '候補保留'
        if not 結果['次作用候補群']:結果['保留理由群'] += 候補.get('保留理由群',[]) or ['現在の全段支持経路がない']
        return 結果
    代替経路 = 候補.get('全条件付き経路群')
    if 代替経路 and not 候補.get('保留理由群'):
        try:
            for 経路 in 代替経路:
                if not 経路.get('合成完了') or not 経路.get('全目標充足') or 経路.get('実行許可') is not False:
                    raise 境界違反('代替経路の目標照合が未成立')
                正規経路 = [_作用候補を共通化する(r, 作用群) for r in 経路['経路作用候補']]
                結果['候補経路群'].append({'語彙': 適用['語彙'], '経路': 正規経路, '根拠': 経路, '実行許可': False})
                if 正規経路:
                    結果['次作用候補群'].append({'語彙': 適用['語彙'], '候補': 正規経路[0], '理由': '支持済み代替経路の先頭。毎手再観測が必要', '実行許可': False})
        except (境界違反, KeyError, TypeError) as exc:
            結果['次作用候補群'] = []; 結果['保留理由群'].append({'代替経路契約': str(exc)})
            結果['状態'] = '候補保留'; return 結果
        結果['状態'] = '条件付き候補' if 結果['次作用候補群'] else '目標充足候補'
        return 結果
    if not 作用:
        結果['状態'] = '複数整合解を保持' if 結果['複数整合解'] else '候補保留'
        結果['保留理由群'] += 候補.get('保留理由群', [])
        if not 結果['複数整合解'] and not 結果['保留理由群']: 結果['保留理由群'].append('現在観測の作用候補が未成立')
        return 結果
    if 候補.get('保留理由群'):
        結果['状態'] = '候補保留'; 結果['保留理由群'] += 候補['保留理由群']; return 結果
    try: 作用 = [_作用候補を共通化する(r, 作用群) for r in 作用]
    except (境界違反, TypeError) as exc:
        結果['状態'] = '候補保留'; 結果['保留理由群'].append({'作用契約': str(exc)}); return 結果
    結果['状態'] = '条件付き候補'
    if 適用['作用候補の意味'] == '順序付き経路':
        結果['候補経路群'].append({'語彙': 適用['語彙'], '経路': 作用, '実行許可': False})
        結果['次作用候補群'].append({'語彙': 適用['語彙'], '候補': 作用[0],
                               '理由': '順序付き経路の先頭。後続は新しい観測で再照会する', '実行許可': False})
    else:
        結果['次作用候補群'] = [{'語彙': 適用['語彙'], '候補': r, '実行許可': False} for r in 作用]
    return 結果


def _画素差分(前, 後):
    if len(前) != len(後) or any(len(a) != len(b) for a, b in zip(前, 後)):
        return {'状態': '寸法変更', '前寸法': [len(前), len(前[0]) if 前 else 0], '後寸法': [len(後), len(後[0]) if 後 else 0]}
    return {'状態': '比較可能', '差分': [{'位置': [x, y], '前': v, '後': 後[y][x]} for y, 行 in enumerate(前) for x, v in enumerate(行) if v != 後[y][x]]}


def 作用応答を相別に記録する(直前, 現在, 作用番号):
    """一回の選択作用と複数応答frameを分離し、途中frameを別Actionに数えない。

    完了数増分は遷移証拠であり解法選択条件ではない。各frameの完成役割は
    目標との照合が必要で、先頭frameを無条件に成功完成と断定しない。
    """
    結果 = {'選択作用番号': 作用番号, '応答全盤面': 現在.盤面列, '作用選択回数': 1,
          '作用応答先頭差分': None, '作用内相間差分群': [], '完成評価候補群': [],
          '完成相採否': {'状態': '未確認', '採用相': None, '理由': '旧問題の構造・目標との照合は未実施'},
          '相の意味': '応答順序のみ確定。作用効果・内部アニメーション・問題切替の境界は未同定',
          '次計画用盤面': 現在.最新盤面, '完了数増分': 現在.完了レベル数 - 直前.完了レベル数,
          '前後公開状態': [直前.状態, 現在.状態], '前後利用可能作用': [直前.作用可能番号, 現在.作用可能番号],
          '保留理由群': [], '因果確定': False,
          '注意': '作用応答先頭、作用内変化、完成候補、次計画状態を別記録。hidden変化は未観測。'}
    if (not 直前.実行識別子 or not 現在.実行識別子 or 直前.実行識別子 != 現在.実行識別子
        or 直前.ゲーム識別子 != 現在.ゲーム識別子):
        結果['保留理由群'].append('同一実行の作用対応を確認できない')
    try: 番号 = _作用番号(作用番号)
    except 境界違反:
        結果['保留理由群'].append('作用番号が不正'); return 結果
    if 番号 == 0 or 現在.全初期化 or 結果['完了数増分'] < 0:
        結果['保留理由群'].append('初期化境界を作用効果と混ぜない')
    if 番号 not in 直前.作用可能番号:
        結果['保留理由群'].append('前観測の利用可能作用として確認できない')
    if 現在.観測通番 <= 直前.観測通番:
        結果['保留理由群'].append('観測順序が進んでいない')
    if not 直前.盤面列 or not 現在.盤面列:
        結果['保留理由群'].append('盤面欠損。公開状態は保持する')
    if 結果['保留理由群']: return 結果
    結果['作用応答先頭差分'] = _画素差分(直前.最新盤面, 現在.盤面列[0])
    結果['作用内相間差分群'] = [{'前相': i, '後相': i + 1, '差分': _画素差分(a, b)}
                           for i, (a, b) in enumerate(zip(現在.盤面列, 現在.盤面列[1:]))]
    if 結果['完了数増分'] > 0:
        結果['完成相採否']['理由'] = '完了増分は観測されたが、旧問題の構造・目標との照合なしでは完成相を一意に決めない'
        結果['完成評価候補群'] = [{'応答相': i, '盤面': f, '採用状態': '旧目標との照合待ち'} for i, f in enumerate(現在.盤面列)]
    return 結果
