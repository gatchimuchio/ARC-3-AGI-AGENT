def _公開値(値):
    if isinstance(値, dict): return {k:_公開値(v) for k,v in 値.items()}
    if isinstance(値, (set, frozenset)): return [_公開値(v) for v in sorted(値)]
    if isinstance(値, (tuple, list)): return [_公開値(v) for v in 値]
    return 値


def _公開結果(関数):
    from functools import wraps
    @wraps(関数)
    def 接続(*args, **kwargs): return _公開値(関数(*args, **kwargs))
    return 接続


def _基本(語彙):
    return {'適用性': {'状態':'未確認','根拠':[]}, '作用適用性': {'状態':'未確認','根拠':[]},
            '目標候補群':[], '作用候補群':[], '作用段階経路群':[], '規則不確実性':[],
            '局所保留群':[], '保留理由群':[], '照会記録':[], '対象群':[], '関係群':[],
            '出所':{'既存語彙':語彙,'同一HDSを注入':True},'実行許可':False}


def _盤面(盤面,作用群):
    # 採用済み形状描画は可変list行を必要とする。外部tupleもここで正規化。
    番号群=tuple(_作用番号(x) for x in 作用群)
    if len(set(番号群))!=len(番号群):raise 境界違反('利用可能作用が重複')
    return [list(r) for r in _盤面列((盤面,))[0]],番号群


def _隔離を記録(結果,系,内容,境界):
    from hds学習系統 import 外部入力
    応答=系.照会する(外部入力(内容,境界))
    結果['照会記録'].append({'入力':内容,'境界':境界,'状態':応答.状態,'内容':応答.内容,'追跡':応答.追跡情報})
    # 公開された係争群だけを全体系の隔離とする。未知条件/予測なしは局所記録。
    if 応答.内容['係争中原理群']:
        結果['規則不確実性'].append({'全体隔離':応答.内容['係争中原理群'],'理由':応答.内容['断定保留理由群']})
    elif 応答.状態=='断定保留':
        結果['局所保留群'].append({'照会入力':内容,'理由':応答.内容['断定保留理由群']})
    return 応答


def _原子(番号,座標=None,根拠=None):
    r={'作用番号':番号,'引数':{} if 座標 is None else {'x':座標[0],'y':座標[1]},'実行許可':False}
    if 根拠 is not None:r['元作用根拠']=根拠
    return r


@_公開結果
def 鎖語彙を接続する(系,盤面,作用群):
    r=_基本('根付き順序鎖');盤面,作用群=_盤面(盤面,作用群);h,w=len(盤面),len(盤面[0])
    # 採用済み鎖画素.parseと同じ必須の可視区切り。解析例外の読み替えではない。
    区切り=[y for y in range(h//2,h-1) if set(盤面[y])=={4} and set(盤面[y+1])=={4} and sum(v in (1,2,3) for v in 盤面[y-1])>=w//2]
    if not 区切り:
        r['適用性']=r['作用適用性']={'状態':'構造上不適用','根拠':['既存鎖文法の全幅凡例区切りが存在しない']};return r
    if len(区切り)!=1:
        r['保留理由群'].append({'区切りが複数':区切り});return r
    場面=鎖画素.parse(盤面)
    r['対象群']=場面['根']+場面['珠'];r['可視構造']=場面
    if not 場面['根'] or not 場面['凡例']:
        r['適用性']=r['作用適用性']={'状態':'構造上不適用','根拠':['既存根/凡例の必須可視構造がない']};return r
    r['適用性']=r['作用適用性']={'状態':'適用可能','根拠':['根と凡例の構造を観測。目標/作用の支持はHDSへ別照会']}
    特徴=next(鎖画素.candidates(場面),None)
    if 特徴 is not None:_隔離を記録(r,系,鎖画素.encode(特徴['特徴']),鎖画素.BOUNDARY)
    元=鎖候補を作る(盤面,作用群,系,照会共有=True);r['原結果']=元;r['目標候補群']=元['目標候補群'];r['全作用候補群']=元['作用候補群'];r['関係群']=元.get('関係群',[])
    r['局所保留群'] += [{'元保留':v} for v in 元['保留理由群']]
    if 場面['未対応画素']:
        r['作用適用性']={'状態':'未確認','根拠':['必要構造はあるが未対応画素を含む']}
    目標状態=set(元.get('探索記録',{}).get('目標状態群',[]))
    for p in 元.get('経路候補群',[]):
        段階=[{'作用候補群':[_原子(s['作用'],根拠=s)],'元段階':s,'実行許可':False} for s in p['手順']]
        終点=p['手順'][-1]['先状態'] if p['手順'] else 0
        r['作用段階経路群'].append({'経路参照':p['経路番号'],'採否':p['採否'],'段階群':段階,
          '全目標充足':終点 in 目標状態,'保留理由群':p['保留作用参照'],'元経路':p,'実行許可':False})
    return r


def 形状作用の範囲を読む(場面,盤面):
    対象,目標=場面['対象'],場面['目標'];正方形=tuple(sorted((x,y) for x in range(3) for y in range(3)))
    if any('未観測枠' in x for x in 目標):return {'状態':'未確認','根拠':['目標輪郭の未観測部分を含む。目標推論の条件付き支持とは別']}
    if len(目標)==2 and all(x['形']==正方形 for x in 目標) and len(対象)!=2 and sum(len(x['点']) for x in 対象)==18:
        return {'状態':'未確認','根拠':['二対象の結合/分解が未同定']}
    if len(対象)!=2 or len(目標)!=2 or any(x['形']!=正方形 for x in 対象+目標) or any(x['色']!=14 for x in 対象) or any(v in (12,13) for row in 盤面 for v in row):
        return {'状態':'構造上不適用','根拠':['既存作用モデルは二つの3×3青対象と二つの可視目標に限定。目標推論の適用性とは別']}
    if sum(x['選択'] for x in 対象)!=1:return {'状態':'未確認','根拠':['選択対象が一意でない']}
    return {'状態':'適用可能','根拠':['既採用の二対象作用モデルの可視前提が一致']}


@_公開結果
def 形状語彙を接続する(系,盤面,作用群):
    r=_基本('形状目標対応と二対象占有');盤面,作用群=_盤面(盤面,作用群)
    if len(盤面)!=64 or len(盤面[0])!=64:r['保留理由群'].append('既存形状知覚は64×64に限定');return r
    場面=形状場面を読む(盤面);r['対象群']=場面['対象'];r['可視構造']=場面
    if not 場面['対象'] or not 場面['目標']:
        r['適用性']=r['作用適用性']={'状態':'構造上不適用','根拠':['既存知覚の対象/目標構造がない']};return r
    r['適用性']={'状態':'適用可能','根拠':['目標対応の対象と輪郭を観測。作用モデルは別判定']}
    r['作用適用性']=形状作用の範囲を読む(場面,盤面)
    _隔離を記録(r,系,{'形状一致':場面['対象'][0]['形']==場面['目標'][0]['形']},目標境界)
    目標=目標対応全候補を読む(盤面,系);r['目標推論']=目標;r['目標候補群']=目標['全候補']
    r['局所保留群'] += [x for x in 目標['全候補'] if x['状態']=='保留']
    if r['作用適用性']['状態']!='適用可能':return r
    元=形状配置を構成する(盤面,系);r['原結果']=元
    if '全状態' not in 元:r['作用適用性']={'状態':'未確認','根拠':[元.get('理由','構成不成立')]};return r
    最短=全体最短経路を読む(元);r['全最短経路']=最短;r['全作用候補群']=元['全辺']
    完成=set(元['全完成状態識別子'])
    辺索引={(g['状態識別子'],e['作用'],e['次状態']):e for g in 元['全辺'] for e in g['四方向と対象内全座標'] if e.get('状態')=='支持'}
    for i,p in enumerate(最短['全体最短経路群']):
        段階=[]
        for s in p:
            e=辺索引[(s['前状態'],s['作用'],s['後状態'])]
            候補=[_原子(6,xy,e) for xy in e['全同値座標']] if s['作用']==6 else [_原子(s['作用'],根拠=e)]
            段階.append({'作用候補群':候補,'元段階':s,'全同値座標を保持':True,'実行許可':False})
        終点=p[-1]['後状態'] if p else 0
        r['作用段階経路群'].append({'経路参照':i,'採否':'全段支持','段階群':段階,'全目標充足':終点 in 完成,'保留理由群':[],'元経路':p,'実行許可':False})
    r['局所保留群'] += [{'状態参照':g['状態識別子'],'候補':e} for g in 元['全辺'] for e in g['四方向と対象内全座標'] if e.get('状態')!='支持']
    return r
