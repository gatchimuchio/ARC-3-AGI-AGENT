許容役割境界='公開図式:複数成功完成が支持する色列内許容役割'

def 許容役割教師を教える(学習系,教師群):
    for 教師 in 教師群:
        応答=学習系.処理する(外部入力(教師['入力'],許容役割境界))
        yield {'教師':教師,'状態':応答.状態,'内容':応答.内容,'根拠':応答.追跡情報}

def _役割照会(学習系,入力,境界,結果名):
    応答=学習系.照会する(外部入力(入力,境界))
    予測=[p for p in 応答.内容['予測群'] if tuple(p['結果経路'])==(結果名,)]
    値={p['予測値'] for p in 予測}
    return (next(iter(値)) if len(値)==1 and 応答.状態!='断定保留' else None),{'状態':応答.状態,'内容':応答.内容}

def 許容集合を含む図式攻略を照会する(盤面,利用可能作用,学習系,適用支持):
    """同一HDSで参照制約と成功完成の許容役割を合成。完成答えは受け取らない。"""
    元=複合図式攻略を照会する(盤面,利用可能作用,学習系,適用支持)
    if 元['適用性']['状態']=='構造上不適用':return 元
    if 元['適用性']['状態']=='未確認' and (not 元['保留理由群'] or any(not isinstance(r,dict) or set(r)!={'未拘束編集対象候補'} for r in 元['保留理由群'])):return 元
    解析=複合図式を読む(盤面)
    if 'HOLD' in 解析 or not 解析.get('未拘束対象群'):return 元
    結果={**元,'適用性':{'状態':'適用可能','根拠':['既存図式構造と条件付き許容役割の照会対象']},'作用候補群':[],'目標候補群':[],'保留理由群':[],
          '照会記録':list(元.get('照会記録',[])),'全条件付き経路群':[],
          '許容集合の範囲':'二色・単一格子参照・標識なし未参照本体・自己対象単独作用。複数成功の存在支持。新問題への転用未検証。',
          '元の保留理由群':元['保留理由群'],'個別保留解消根拠':[],'実行許可':False}
    保留=結果['保留理由群'];照会=結果['照会記録']
    if 元.get('規則の不確実性'):
        保留.extend(元['保留理由群']);return 結果
    if 6 not in 利用可能作用:保留.append('座標作用が利用可能と確認できない')
    対象群=本体対象群を読む(盤面,解析);鍵群=sorted(対象群)
    許容={k:set(解析['色列']) for k in 鍵群};参照数={k:0 for k in 鍵群}
    for 参照 in 解析['参照対象群']:
        鍵=tuple(参照['対象位置'])
        値,記録=_役割照会(学習系,{'指示記号順位':参照['記号順位']},解答境界,'解答対象役割');照会.append(記録)
        if 参照['役割'] not in ('単色','装飾付き'):
            if 値!='成功解で直接配色割当なし' or 参照['役割'] not in ('画面外','背景','指示小図'):保留.append({'非配色参照未支持':参照,'照会':記録})
            continue
        if 鍵 not in 対象群:保留.append({'対象未対応':参照});continue
        参照数[鍵]+=1
        if 値=='中心色一致':許容[鍵]&={参照['中心色']}
        elif 値=='中心色非一致':許容[鍵]-={参照['中心色']}
        else:保留.append({'解答役割未支持':参照,'照会':記録})
    解消=set()
    for 鍵 in 鍵群:
        if 参照数[鍵]:continue
        連動,不明,記録=連動対象群を照会する(学習系,対象群,対象群[鍵],標識色群=適用支持['標識色群']);照会+=記録
        範囲保留=許容集合適用保留(解析,対象群[鍵],参照数[鍵],連動,不明)
        if 範囲保留:保留.append({'対象':鍵,'許容役割適用保留':範囲保留});continue
        値,記録=_役割照会(学習系,{'図式から参照される':False},許容役割境界,'成功完成で色列全色の支持あり');照会.append(記録)
        if 値 is not True:保留.append({'許容役割未支持':鍵,'照会':記録});continue
        解消.add(鍵);結果['個別保留解消根拠'].append({'対象':鍵,'照会':記録,'許容色集合':sorted(許容[鍵])})
    for 理由 in 解析['適用保留理由群']:
        if not isinstance(理由,dict) or set(理由)!={'未拘束編集対象候補'} or set(map(tuple,理由['未拘束編集対象候補']))!=解消:保留.append(理由)
    作用列=[]
    for 鍵 in 鍵群:
        連動,不明,記録=連動対象群を照会する(学習系,対象群,対象群[鍵],標識色群=適用支持['標識色群']);保留+=不明;照会+=記録
        作用列.append(sum(1<<鍵群.index(k) for k in 連動))
    if any(not v for v in 許容.values()):保留.append('目標制約の共通許容色がない')
    結果['目標候補群']=[{**対象群[k],'許容色集合':sorted(許容[k])} for k in 鍵群]
    結果['規則の不確実性'] += [q for q in 照会 if q.get('状態')=='断定保留']
    if 保留:return 結果
    経路群=結果['全条件付き経路群']
    for 色群 in itertools.product(*(sorted(許容[k]) for k in 鍵群)):
        目標差分=sum((対象群[k]['本体色']!=c)<<i for i,(k,c) in enumerate(zip(鍵群,色群)))
        解=二色制約を解く(作用列,目標差分,len(鍵群))
        if 解 is None:
            結果.setdefault('未採用候補と理由',[]).append({'許容目標':list(色群),'理由':'支持作用では到達不能'});continue
        偶奇群={解['特解']}
        for 基底 in 解['同次解基底']:偶奇群|={x^基底 for x in list(偶奇群)}
        for 偶奇 in sorted(偶奇群):
            経路=条件付き操作を合成する(鍵群,{k:c['本体色'] for k,c in 対象群.items()},許容,作用列,偶奇,lambda 色:次色を照会する(学習系,解析['色列'],色))
            経路.update({'許容目標':list(色群),'操作偶奇':偶奇})
            経路['経路作用候補']=[{'作用番号':6,'座標':[手['対象'][0]+対象群[手['対象']]['幅']//2,手['対象'][1]+対象群[手['対象']]['幅']//2],'全対象予測差分':手['予測差分'],'実行許可':False} for 手 in 経路['作用候補']]
            経路群.append(経路)
            保留+=経路['保留条件']
    if not 経路群 or any(not p['全目標充足'] for p in 経路群):保留.append('全候補経路の合成/目標照合が完了していない')
    結果['複数整合解']={'候補数':len(経路群),'候補集合':経路群}
    # 複数経路を旧APIの一つの順序付き経路へ結合しない。全候補を保持する。
    結果['候補選択状態']='各整合経路の先頭を代替候補として保持。経路の優先順位は付けない'
    return 結果
