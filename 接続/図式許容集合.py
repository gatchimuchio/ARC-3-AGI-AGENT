"""複数の公開成功完成が支持する条件付き許容集合。"""
def 許容集合適用保留(解析, 対象, 参照数, 連動対象群, 連動保留):
    理由 = []
    if len(解析.get('色列', [])) != 2: 理由.append('教師支持は観測二色列に限定')
    if len(解析.get('格子位相群', [])) != 1 or not 解析.get('参照対象群'): 理由.append('指示小図と格子参照の対応が未確認')
    if 参照数 != 0: 理由.append('既存参照制約がある対象への許容集合拡張は禁止')
    if 対象.get('標識画素'): 理由.append('未参照対象の教師支持は標識なし本体に限定')
    if 連動保留 or set(連動対象群) != {tuple(対象['位置'])}: 理由.append('教師で支持された対象単独の作用役割を確認できない')
    return 理由

def 条件付き操作を合成する(鍵群, 本体色, 許容色群, 作用列, 操作偶奇, 次色照会):
    状態 = dict(本体色); 手順 = []; 保留 = []
    for j, 鍵 in enumerate(鍵群):
        if not (操作偶奇 >> j) & 1: continue
        予測差分 = []; 手保留 = []
        for i, 対象 in enumerate(鍵群):
            if not (作用列[j] >> i) & 1: continue
            q = 次色照会(状態[対象])
            if q.get('状態') == 'HOLD' or '次色' not in q:
                手保留.append({'対象': 対象, '照会': q}); continue
            予測差分.append({'対象': 対象, '前': 状態[対象], '後': q['次色'], '照会': q})
        手順.append({'対象': 鍵, '予測差分': 予測差分, '保留条件': 手保留})
        if 手保留:
            保留 += 手保留
            # 一部の同時差分だけ更新した状態から後続を合成しない。
            break
        for d in 予測差分: 状態[d['対象']] = d['後']
    return {'作用候補': 手順, '終端': [[*k, 状態[k]] for k in 鍵群], '保留条件': 保留,
            '合成完了': not 保留, '全目標充足': not 保留 and all(状態[k] in 許容色群[k] for k in 鍵群), '実行許可': False}

