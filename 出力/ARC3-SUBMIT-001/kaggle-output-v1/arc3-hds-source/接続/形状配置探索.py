"""同じ一個のHDSだけで構造適用する全探索API。外部環境は操作しない。"""
from collections import deque as 待ち行列, defaultdict as 既定辞書
from .形状配置知覚 import 形状場面を読む, 全整合分解を読む, 外接矩形, 盤面を検査する
from .形状配置規則 import 方向候補, 目標境界, 局所境界, 投射境界, 選択境界, 規則を照会する, 局所前提を読む, 局所前提を符号化する, 投射前提を読む

def 形状配置を構成する(盤面, 学習系):
    盤面を検査する(盤面)
    場面 = 形状場面を読む(盤面)
    対象群 = 場面['対象']
    目標群 = 場面['目標']
    if any((対象['色'] != 14 for 対象 in 対象群)) or any((値 in (12, 13) for row in 盤面 for 値 in row)):
        return {'状態': '保留', '理由': '現モデル未対応の非青対象または搬送候補がある。候補を埋めない。','実行許可':False,'新規環境成功':False}
    支持形 = tuple(sorted((x,y) for x in range(3) for y in range(3)))
    if len(対象群)!=2 or len(目標群)!=2 or any(対象['形']!=支持形 for 対象 in 対象群) or any(目標['形']!=支持形 or '未観測枠' in 目標 for 目標 in 目標群):
        return {'状態':'保留','理由':'現在の復元モデルの支持範囲は二つの3×3青対象と二つの可視閉輪郭。未支持の分解/描画を補わない。','観測':場面,'実行許可':False,'新規環境成功':False}
    選択索引群 = [番号 for 番号, 対象 in enumerate(対象群) if 対象['選択']]
    if len(選択索引群) != 1:
        return {'状態': '保留', '理由': '選択対象不明','実行許可':False,'新規環境成功':False}
    形群 = [対象['形'] for 対象 in 対象群]
    復元背景 = [row[:] for row in 盤面]
    for 対象 in 対象群:
        for x, y in 対象['点']:
            復元背景[y][x] = 1
    for 目標 in 目標群:
        for x, y in 目標['外枠']:
            復元背景[y][x] = 4

    def 状態を描画する(状態):
        位置群, 選択索引 = 状態
        描画盤面 = [row[:] for row in 復元背景]
        再観測対象群 = []
        for 番号, (形, 位置) in enumerate(zip(形群, 位置群)):
            画素群 = {(位置[0] + x, 位置[1] + y) for x, y in 形}
            対象 = {'色': 14, '点': 画素群, '形': 形, '位置': 位置, '選択': 番号 == 選択索引}
            再観測対象群.append(対象)
            for x, y in 画素群:
                描画盤面[y][x] = 14
            x, y, X, Y = 外接矩形(画素群)
            cx, cy = ((x + X) // 2, (y + Y) // 2)
            描画盤面[cy][cx] = 0 if 番号 == 選択索引 else 4 if any((画素群 == 項目['点'] for 項目 in 目標群)) else 5
        return (描画盤面, 再観測対象群)
    選択照会 = 規則を照会する(学習系, {'座標がこの対象に含まれる': True}, 選択境界, '作用後この対象が選択される')
    移動照会記憶 = {}
    投射照会記憶 = {}
    目標照会記憶 = {}

    def 移動を照会する(前状態特徴):
        入力 = 局所前提を符号化する(前状態特徴, '直積記号')
        鍵 = str(入力)
        if 鍵 not in 移動照会記憶:
            移動照会記憶[鍵] = 規則を照会する(学習系, 入力, 局所境界, '入力方向へ一単位進む')
        return 移動照会記憶[鍵]

    def 投射を照会する(描画盤面, 候補, 要素, 作用番号):
        入力 = 投射前提を読む(描画盤面, 候補, 要素, 作用番号)
        鍵 = str(入力)
        if 鍵 not in 投射照会記憶:
            投射照会記憶[鍵] = 規則を照会する(学習系, 入力, 投射境界, '接触対象変位')
        return 投射照会記憶[鍵]
    始点 = (tuple((tuple(対象['位置']) for 対象 in 対象群)), 選択索引群[0])
    状態群 = [始点]
    識別索引 = {始点: 0}
    待機列 = 待ち行列([0])
    最短距離 = {0: 0}
    全前駆 = 既定辞書(list)
    辺群 = []
    完成識別子群 = []
    完成構造群 = []
    全分解記録 = []
    while 待機列:
        状態識別子 = 待機列.popleft()
        状態 = 状態群[状態識別子]
        描画盤面, 再観測対象群 = 状態を描画する(状態)
        位置群, 選択番号 = 状態
        分解候補群 = 全整合分解を読む(描画盤面, 形群)
        全分解記録.append({"状態識別子":状態識別子,"全可視分解":分解候補群})
        if len(分解候補群) != 1:
            辺群.append({'状態識別子': 状態識別子, '四方向と対象内全座標': [{'作用': 作用番号, '状態': '保留', '次状態': None, '理由': '可視分解が一意でない', '全可視分解': 分解候補群} for 作用番号 in 方向候補], '対象外全座標': '全4096座標保留。対象包含が確定しない。'})
            continue
        観測済み = {(対象['形'], 対象['位置']): 対象 for 対象 in 分解候補群[0]}
        if any(((形, tuple(位置)) not in 観測済み for 形, 位置 in zip(形群, 位置群))):
            raise AssertionError('可視分解が予測構造と一致しない')
        再観測対象群 = [観測済み[形, tuple(位置)] for 形, 位置 in zip(形群, 位置群)]
        assert 再観測対象群[選択番号]['選択']
        選択対象 = 再観測対象群[選択番号]
        対応群 = []
        for 関係 in [False, True]:
            if 関係 not in 目標照会記憶:
                目標照会記憶[関係] = 規則を照会する(学習系, {'形状一致': 関係}, 目標境界, '成功占有形と対応')['値']
        for 目標 in 目標群:
            対応群.append([番号 for 番号, 対象 in enumerate(再観測対象群) if 対象['点'] == 目標['点'] and 目標照会記憶[対象['形'] == 目標['形']] is True])
        if 対応群 and len(対応群) == len(再観測対象群) and all((len(m) == 1 for m in 対応群)) and (len({m[0] for m in 対応群}) == len(再観測対象群)):
            完成識別子群.append(状態識別子)
            完成構造群.append({'状態識別子': 状態識別子, '対象位置': 位置群, '目標占有': 対応群})
        作用群 = []
        for 番号, 対象 in enumerate(再観測対象群):
            作用群.append({'作用': 6, '全同値座標': sorted(対象['点']), '状態': '支持' if 選択照会['値'] is True else '保留', '次': (位置群, 番号) if 選択照会['値'] is True else None, '根拠': 選択照会['予測']})
        for 作用番号, (dx, dy) in 方向候補.items():
            入力 = 局所前提を読む(描画盤面, 選択対象, 作用番号)
            参照値 = 移動を照会する(入力)
            foot = {(x + dx, y + dy) for x, y in 選択対象['点']}
            接触群 = [対象番号 for 対象番号, 対象 in enumerate(再観測対象群) if 対象番号 != 選択番号 and foot & 対象['点']]
            次位置群 = list(位置群)
            理由 = None
            支持群 = []
            if 参照値['値'] is None:
                理由 = '局所移動HDS 保留'
            elif 参照値['値'] is True:
                次位置群[選択番号] = (位置群[選択番号][0] + dx, 位置群[選択番号][1] + dy)
                支持群 += 参照値['予測']
            else:
                支持群 += 参照値['予測']
            if 接触群:
                if len(接触群) != 1:
                    理由 = '複数対象への同時接触未同定'
                else:
                    対象番号 = 接触群[0]
                    投射照会 = 投射を照会する(描画盤面, 選択対象, 再観測対象群[対象番号], 作用番号)
                    if 投射照会['値'] is None:
                        理由 = '接触投射HDS 保留'
                    else:
                        fw, sd = map(int, 投射照会['値'].split(','))
                        ux, uy = (dx // 3, dy // 3)
                        次位置群[対象番号] = (位置群[対象番号][0] + fw * ux - sd * uy, 位置群[対象番号][1] + fw * uy + sd * ux)
                        支持群 += 投射照会['予測']
            次状態 = (tuple(次位置群), 選択番号)
            if 理由 is None:
                領域群 = [{(位置[0] + x, 位置[1] + y) for x, y in 形} for 位置, 形 in zip(次位置群, 形群)]
                if any((any((not (0 <= x < 64 and 0 <= y < 64) for x, y in 領域)) for 領域 in 領域群)) or any((領域群[番号] & 領域群[対象番号] for 番号 in range(len(領域群)) for 対象番号 in range(番号 + 1, len(領域群)))):
                    理由 = '予測後状態の境界/非重複制約違反'
            作用群.append({'作用': 作用番号, '状態': '保留' if 理由 else '支持', '保留理由': 理由, '次': None if 理由 else 次状態, '根拠': 支持群, '前状態関係': 入力})
        状態辺群 = []
        for 候補 in 作用群:
            次状態候補 = 候補.pop('次')
            次識別子 = None
            if 次状態候補 is not None:
                if 次状態候補 not in 識別索引:
                    識別索引[次状態候補] = len(状態群)
                    状態群.append(次状態候補)
                    最短距離[識別索引[次状態候補]] = 最短距離[状態識別子] + 1
                    待機列.append(識別索引[次状態候補])
                次識別子 = 識別索引[次状態候補]
                if 最短距離[次識別子] == 最短距離[状態識別子] + 1:
                    全前駆[次識別子].append({'前状態': 状態識別子, '作用': 候補['作用'], '座標代表': 候補.get('全同値座標', [None])[0]})
            状態辺群.append({**候補, '次状態': 次識別子})
        辺群.append({'状態識別子': 状態識別子, '四方向と対象内全座標': 状態辺群, '対象外全座標': '64x64格子から上記対象内座標を除く全点は保留。選択以外の座標作用未同定。'})
    return {'状態': '条件付き完成候補あり' if 完成識別子群 else '保留', '初期状態': 始点, '全状態': [{'状態識別子': 番号, '対象位置': s[0], '選択対象': s[1], '最短作用数': 最短距離[番号], '全最短前駆': 全前駆[番号]} for 番号, s in enumerate(状態群)], '全辺': 辺群, '全観測分解':全分解記録, '全完成状態': 完成構造群, '全完成状態識別子': 完成識別子群, 'HDS照会キャッシュ': {'移動': list(移動照会記憶.values()), '投射': list(投射照会記憶.values())}, '状態描画仮定': '青対象移動跡を床/既知輪郭へ復帰。14充填に0/5/4代表マーカーを描く。矢印マーカー/HUD画素は再現しない。', '実行許可': False, '新規環境成功': False, '完全探索': True}


def 全体最短経路を読む(構成):
    """全4終点の全最短親は元の全状態に保持。全体最短8経路も列挙する。"""
    状態群=構成.get('全状態',[]);終点群=構成.get('全完成状態識別子',[])
    if not 終点群:return {'最短作用数':None,'全体最短経路群':[],'全終点最短距離':[]}
    最小=min(状態群[終点]['最短作用数'] for 終点 in 終点群)
    経路群=[]
    def 遡る(識別子,逆経路):
        if 識別子==0:
            経路群.append(list(reversed(逆経路)));return
        for 前駆 in 状態群[識別子]['全最短前駆']:
            遡る(前駆['前状態'],逆経路+[{**前駆,'後状態':識別子}])
    for 終点 in 終点群:
        if 状態群[終点]['最短作用数']==最小:遡る(終点,[])
    return {'最短作用数':最小,'全体最短経路群':経路群,
            '全終点最短距離':[{'終点':終点,'最短作用数':状態群[終点]['最短作用数']} for 終点 in 終点群]}
